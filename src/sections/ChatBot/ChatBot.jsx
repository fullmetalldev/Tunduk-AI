import { useEffect, useRef, useState } from "react";
import { Visualizer } from "../../components/Visualizer/Visualizer.jsx";
import AudioVolumeMeter from "../../components/Visualizer/AudioVolumeMeter.jsx";
import "./ChatBot.scss";
import Logo from "../../components/Logo/Logo.jsx";
import YurtIcon from "../../assets/Yurt.jsx";
import Button from "../../components/Button/Button.jsx";
import DroppCall from "../../lib/callDrop.wav";
import JoinCall from "../../lib/callJoin.wav";
import SpeechToText from "../../hooks/SpeechToText.jsx";
import { useBotReply } from "../../hooks/useBotReply.js";
import ChatMessages from "../../components/ChatMessages/ChatMessages.jsx";
import { DEFAULT_VOICE_ID, VOICES } from "../../api/ElevenLabs.js";
import { useI18n } from "../../i18n/useI18n";

const VOICE_STORAGE_KEY = "voiceId";

const getInitialVoice = () => {
  try {
    const saved = localStorage.getItem(VOICE_STORAGE_KEY);
    if (VOICES.some((voice) => voice.id === saved)) return saved;
  } catch {
    // localStorage unavailable - fall back to default
  }
  return DEFAULT_VOICE_ID;
};

const ChatBot = () => {
  const { t } = useI18n();
  const currentAudioRef = useRef(null);
  const joinCallRef = useRef(null);
  const dropCallRef = useRef(null);
  const blobUrlRef = useRef(null);
  const [volume, setVolume] = useState(0);
  const [botState, setBotState] = useState("idle");
  const [voiceId, setVoiceId] = useState(getInitialVoice);
  // What the user is saying right now, for live captions
  const [partial, setPartial] = useState("");
  const { reply, respond, cancel: cancelReply } = useBotReply();

  useEffect(() => {
    try {
      localStorage.setItem(VOICE_STORAGE_KEY, voiceId);
    } catch {
      // ignore
    }
  }, [voiceId]);

  // Handle when bot finishes speaking (or its audio fails to play)
  useEffect(() => {
    const audio = currentAudioRef.current;
    if (!audio) return;

    const handleEnded = () => {
      // Go back to listening so user can speak again without clicking button
      setBotState((state) => (state === "speaking" ? "listening" : state));
    };

    audio.addEventListener("ended", handleEnded);
    audio.addEventListener("error", handleEnded);

    return () => {
      audio.removeEventListener("ended", handleEnded);
      audio.removeEventListener("error", handleEnded);
    };
  }, []);

  const releaseBlobUrl = () => {
    if (blobUrlRef.current) {
      URL.revokeObjectURL(blobUrlRef.current);
      blobUrlRef.current = null;
    }
  };

  const stopBotAudio = () => {
    const audio = currentAudioRef.current;
    if (audio) {
      audio.pause();
      audio.removeAttribute("src");
      audio.load();
    }
    releaseBlobUrl();
  };

  const startConversation = () => {
    cancelReply();
    setPartial("");
    if (botState === "idle") {
      joinCallRef.current.play();
      setBotState("connecting");
    } else {
      stopBotAudio();
      dropCallRef.current.play();
      setBotState("idle");
    }
  };

  const playBotAudio = (audioUrl) => {
    setBotState((state) => (state === "thinking" ? "speaking" : state));
    handleAudioGenerated(audioUrl);
  };

  // The user finished a phrase during a call: answer out loud
  const handleUtterance = async (text) => {
    setPartial("");
    setBotState("thinking");
    let spoke = false;
    try {
      spoke = await respond(text, { voiceId, onSpeech: playBotAudio });
    } catch (error) {
      console.error("Error generating bot response:", error);
    }
    // No audio (or an error): go back to listening so user can try again
    if (!spoke) {
      setBotState((state) => (state === "thinking" ? "listening" : state));
    }
  };


  // Handle when audio is generated by bot
  const handleAudioGenerated = (audioUrl) => {
    const audio = currentAudioRef.current;
    if (!audio) return;
    console.log("Playing bot audio:", audioUrl);

    releaseBlobUrl();
    if (audioUrl.startsWith("blob:")) blobUrlRef.current = audioUrl;

    audio.src = audioUrl;
    audio.play().catch((error) => {
      console.error("Error playing bot audio:", error);
      setBotState((state) => (state === "speaking" ? "listening" : state));
    });
  };

  const buttonLabel = t(`chat.state.${botState}`);

  return (
    <>
      <audio hidden controls src={DroppCall} ref={dropCallRef} />
      <audio hidden controls src={JoinCall} ref={joinCallRef} />
      <audio hidden controls ref={currentAudioRef} />
      <AudioVolumeMeter
        audioRef={currentAudioRef}
        volume={volume}
        setVolume={setVolume}
      />

      <section className="ChatBot">
        <div className="container">
          <div className="ChatBot__chatBox">
            <div className="ChatBot__chatBox_header">
              <div className="ChatBot__chatBox_header-buttons">
                <div className="circle bg-red"></div>
                <div className="circle bg-yellow"></div>
                <div className="circle bg-green"></div>
              </div>
              <div className="ChatBot__chatBox_header-info">
                <Logo />
                <span>v1.0 Beta</span>
              </div>
            </div>

            <div className="ChatBot__chatBox_content">
              <div className="ChatBot__chatBox_content-bot">
                <SpeechToText
                  setBotState={setBotState}
                  botState={botState}
                  onPartial={setPartial}
                  onUtterance={handleUtterance}
                />
                <YurtIcon className={botState} />
                {currentAudioRef && (
                  <Visualizer
                    state={botState}
                    volume={volume}
                    audioRef={currentAudioRef}
                  />
                )}
              </div>

              <div className="ChatBot__chatBox_chat">
                <label className="ChatBot__chatBox_voice">
                  <span>{t("chat.voice")}</span>
                  <select
                    value={voiceId}
                    onChange={(e) => setVoiceId(e.target.value)}
                  >
                    {VOICES.map((voice) => (
                      <option key={voice.id} value={voice.id}>
                        {voice.name}
                      </option>
                    ))}
                  </select>
                </label>
                <Button
                  className={botState === "idle" ? "bg-green" : "bg-red"}
                  onClick={() => startConversation()}
                >
                  {buttonLabel}
                </Button>
              </div>

              <ChatMessages reply={reply} partial={partial} />
            </div>
          </div>
        </div>
      </section>
    </>
  );
};
export default ChatBot;
